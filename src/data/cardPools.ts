/**
 * Get random cards from a pool
 * @param categoryId - Category ID
 * @param count - Number of cards to select (default 8)
 * @returns Array of randomly selected cards
 */
export function getRandomCards(categoryId: string, count: number = 8): Card[] {
  const pool = CARD_POOLS[categoryId];
  if (!pool) {
    console.warn(`No card pool found for category: ${categoryId}`);
    return [];
  }

  // Shuffle array using Fisher-Yates algorithm
  const shuffled = [...pool];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  // Return first N cards
  return shuffled.slice(0, Math.min(count, shuffled.length));
}

/**
 * Get all cards for a category (for testing or full view)
 */
export function getAllCards(categoryId: string): Card[] {
  return CARD_POOLS[categoryId] || [];
}
